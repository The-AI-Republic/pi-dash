# Regenerates pidash-msi-lifecycle.wxi from pidash-msi-lifecycle.ps1.
#
# main.wxs runs the helper as
#   powershell.exe ... -Command "[PidashLifecycleRun] -Mode <mode> -BinDir '[Bin]'"
# Windows Installer substitutes [PidashLifecycleRun] verbatim, so the property
# holds a ready-to-run PowerShell expression: decode the embedded script and
# invoke it. It lives in the Property table because CustomAction.Target is
# limited to 255 characters.
#
# Line endings are normalized to LF so a CRLF checkout embeds the same bytes;
# runner/tests/pidash_msi_lifecycle_test.ps1 fails if this file is stale.

param(
    [string] $Script = (Join-Path $PSScriptRoot 'pidash-msi-lifecycle.ps1'),
    [string] $Output = (Join-Path $PSScriptRoot 'pidash-msi-lifecycle.wxi')
)

$ErrorActionPreference = 'Stop'
$text = [System.IO.File]::ReadAllText((Resolve-Path $Script).Path) -replace "`r`n", "`n"
$encoded = [Convert]::ToBase64String([System.Text.Encoding]::Unicode.GetBytes($text))
$run = "&([scriptblock]::Create([Text.Encoding]::Unicode.GetString([Convert]::FromBase64String('$encoded'))))"
$value = [System.Security.SecurityElement]::Escape($run)

$wxi = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by update-msi-lifecycle.ps1 from pidash-msi-lifecycle.ps1. Do not edit. -->
<Include>
    <Property Id="PidashLifecycleRun" Value="$value"/>
</Include>

"@ -replace "`r`n", "`n"
[System.IO.File]::WriteAllText($Output, $wxi, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Output"
