# Behavioral tests for wix/pidash-msi-lifecycle.ps1 and its MSI wiring.
#
# Stop is tested against real processes: a stand-in pidash.exe is compiled,
# copied into a fake MSI bin directory and a fake second installation, and
# the test checks that the MSI's executable is actually released (the failure
# Windows Installer reported as "Files in Use"). Restart and Uninstall use
# fake ScheduledTasks cmdlets, so the real Task Scheduler is never changed.
# The helper always runs in a Windows PowerShell 5.1 child, as under msiexec.
#
# After editing wix/pidash-msi-lifecycle.ps1, run this with -Update to
# regenerate wix/pidash-msi-lifecycle.wxi, the copy embedded in the MSI.

param(
    [string] $Helper = (Join-Path $PSScriptRoot '..\wix\pidash-msi-lifecycle.ps1'),
    [string] $WixSource = (Join-Path $PSScriptRoot '..\wix\main.wxs'),
    [string] $WixInclude = (Join-Path $PSScriptRoot '..\wix\pidash-msi-lifecycle.wxi'),
    [switch] $Update
)

$ErrorActionPreference = 'Stop'
$helper = (Resolve-Path $Helper).Path

# main.wxs runs the helper as
#   powershell.exe ... -Command "[PidashLifecycleRun] -Mode <mode> -BinDir '[Bin]'"
# Windows Installer substitutes [PidashLifecycleRun] verbatim, so the property
# holds a ready-to-run expression that decodes and invokes the script. It is a
# Property because CustomAction.Target is limited to 255 characters. Line
# endings are normalized so a CRLF checkout embeds the same bytes.
function Get-LifecycleInclude {
    $text = [System.IO.File]::ReadAllText($helper) -replace "`r`n", "`n"
    $encoded = [Convert]::ToBase64String([System.Text.Encoding]::Unicode.GetBytes($text))
    $run = "&([scriptblock]::Create([Text.Encoding]::Unicode.GetString([Convert]::FromBase64String('$encoded'))))"
    $value = [System.Security.SecurityElement]::Escape($run)
    @(
        '<?xml version="1.0" encoding="utf-8"?>'
        '<!-- Generated by runner/tests/pidash_msi_lifecycle_test.ps1 -Update from pidash-msi-lifecycle.ps1. Do not edit. -->'
        '<Include>'
        "    <Property Id=""PidashLifecycleRun"" Value=""$value""/>"
        '</Include>'
        ''
    ) -join "`n"
}

if ($Update) {
    [System.IO.File]::WriteAllText($WixInclude, (Get-LifecycleInclude), (New-Object System.Text.UTF8Encoding($false)))
    Write-Output "wrote $WixInclude"
    exit 0
}

$shell = "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe"
$work = Join-Path ([System.IO.Path]::GetTempPath()) "pidash-msi-lifecycle-test-$([guid]::NewGuid())"
$binDir = Join-Path $work 'msi-bin'
$otherDir = Join-Path $work 'other-bin'
$stateDir = Join-Path $work 'state'
$msiExe = Join-Path $binDir 'pidash.exe'
$otherExe = Join-Path $otherDir 'pidash.exe'
$marker = Join-Path $stateDir 'msi-restart-runner'
New-Item -ItemType Directory -Path $binDir,$otherDir,$stateDir | Out-Null

$testVariables = 'PIDASH_LIFECYCLE_TEST_TASK', 'PIDASH_LIFECYCLE_TEST_TARGET', 'PIDASH_LIFECYCLE_TEST_START'
$originalVariables = @{}
foreach ($name in $testVariables) { $originalVariables[$name] = [Environment]::GetEnvironmentVariable($name) }
$failures = New-Object System.Collections.Generic.List[string]
$passed = 0

# Fake ScheduledTasks cmdlets. They write with Write-Host so they cannot leak
# into the helper's return values. Start-ScheduledTask really starts the
# stand-in runner, so the helper's wait-for-runner loop is exercised too.
$fakeTasks = @'
function Get-ScheduledTask {
    [CmdletBinding()]
    param([string] $TaskName, [string] $TaskPath)
    switch ($env:PIDASH_LIFECYCLE_TEST_TASK) {
        'missing' { return }
        'error' { throw 'fake query failure' }
    }
    [pscustomobject]@{
        Actions = @([pscustomobject]@{ Execute = $env:PIDASH_LIFECYCLE_TEST_TARGET })
        Settings = [pscustomobject]@{ Enabled = ($env:PIDASH_LIFECYCLE_TEST_TASK -ne 'disabled') }
    }
}
function Start-ScheduledTask {
    [CmdletBinding()]
    param($InputObject)
    if ($env:PIDASH_LIFECYCLE_TEST_START -eq 'deny') { throw 'Access is denied.' }
    Write-Host 'FAKE-START'
    Start-Process -FilePath $env:PIDASH_LIFECYCLE_TEST_TARGET.Trim('"') -ArgumentList '__run' -WindowStyle Hidden
}
function Stop-ScheduledTask {
    [CmdletBinding()]
    param($InputObject)
    Write-Host 'FAKE-STOP'
}
function Unregister-ScheduledTask {
    [CmdletBinding()]
    param($InputObject, [switch] $Confirm)
    Write-Host 'FAKE-REMOVE'
}
'@

function Assert-Case([string] $name, [bool] $condition, [string] $detail) {
    if ($condition) {
        $script:passed++
        Write-Output "  ok   $name"
    } else {
        $script:failures.Add("$name`n$detail")
        Write-Output "  FAIL $name"
    }
}

function Invoke-Helper([string] $mode, [hashtable] $fake = @{}) {
    foreach ($name in $testVariables) { Remove-Item "Env:\$name" -ErrorAction SilentlyContinue }
    if ($fake.Task) { $env:PIDASH_LIFECYCLE_TEST_TASK = $fake.Task }
    if ($fake.Target) { $env:PIDASH_LIFECYCLE_TEST_TARGET = $fake.Target }
    if ($fake.Start) { $env:PIDASH_LIFECYCLE_TEST_START = $fake.Start }
    $command = "$fakeTasks`n& '$helper' -Mode $mode -BinDir '$binDir' -StateDir '$stateDir' -TimeoutSeconds 10`nexit `$LASTEXITCODE"
    $encoded = [Convert]::ToBase64String([System.Text.Encoding]::Unicode.GetBytes($command))
    $ErrorActionPreference = 'Continue'
    $output = & $shell -NoProfile -NonInteractive -EncodedCommand $encoded 2>&1 | Out-String
    $code = $LASTEXITCODE
    $ErrorActionPreference = 'Stop'
    [pscustomobject]@{ Code = $code; Output = $output }
}

function Start-StandIn([string] $exe, [string] $arguments) {
    Start-Process -FilePath $exe -ArgumentList $arguments -WindowStyle Hidden -PassThru
}

function Test-Alive([int] $id) {
    $null -ne (Get-Process -Id $id -ErrorAction SilentlyContinue)
}

# The file Windows Installer must overwrite is free only when no process maps
# it, which an exclusive read/write open detects.
function Test-Released([string] $path) {
    try {
        $stream = [System.IO.File]::Open($path, 'Open', 'ReadWrite', 'None')
        $stream.Dispose()
        return $true
    } catch {
        return $false
    }
}

function Wait-Child([int] $parentId) {
    $deadline = (Get-Date).AddSeconds(10)
    while ((Get-Date) -lt $deadline) {
        $child = Get-CimInstance -ClassName Win32_Process -Filter "ParentProcessId=$parentId" |
            Where-Object { $_.Name -eq 'PING.EXE' }
        if ($child) { return [int] $child.ProcessId }
        Start-Sleep -Milliseconds 200
    }
    throw "stand-in runner $parentId did not start its agent process"
}

function Stop-TestProcesses {
    Get-CimInstance -ClassName Win32_Process |
        Where-Object { $_.ExecutablePath -and $_.ExecutablePath.StartsWith($work, [System.StringComparison]::OrdinalIgnoreCase) } |
        ForEach-Object {
            Get-CimInstance -ClassName Win32_Process -Filter "ParentProcessId=$($_.ProcessId)" |
                ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
            Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue
        }
    Start-Sleep -Milliseconds 300
}

try {
    # A stand-in pidash.exe that idles like the runner. With "spawn" it starts
    # a long ping as its agent process. Compiled in Windows PowerShell 5.1,
    # because PowerShell 7's Add-Type cannot emit executables.
    $standIn = Join-Path $work 'standin.exe'
    $source = @'
public static class StandIn {
    public static void Main(string[] args) {
        if (System.Array.IndexOf(args, "spawn") >= 0) {
            var start = new System.Diagnostics.ProcessStartInfo(
                System.Environment.ExpandEnvironmentVariables(@"%SystemRoot%\System32\PING.EXE"),
                "-n 600 127.0.0.1");
            start.UseShellExecute = false;
            start.CreateNoWindow = true;
            System.Diagnostics.Process.Start(start);
        }
        System.Threading.Thread.Sleep(System.Threading.Timeout.Infinite);
    }
}
'@
    # From a file: antivirus command-line scanning refuses to start a
    # PowerShell whose encoded command carries C# source.
    $sourceFile = Join-Path $work 'standin.cs'
    $compileFile = Join-Path $work 'compile.ps1'
    Set-Content -LiteralPath $sourceFile -Value $source
    Set-Content -LiteralPath $compileFile -Value "Add-Type -Path '$sourceFile' -OutputAssembly '$standIn' -OutputType ConsoleApplication"
    & $shell -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $compileFile | Out-Null
    if (-not (Test-Path -LiteralPath $standIn)) { throw 'could not compile the stand-in pidash.exe' }
    Copy-Item -LiteralPath $standIn -Destination $msiExe
    Copy-Item -LiteralPath $standIn -Destination $otherExe

    Write-Output 'Stop: runner with an agent, plus another installation'
    $runner = Start-StandIn $msiExe '__run spawn'
    $agent = Wait-Child $runner.Id
    $otherRunner = Start-StandIn $otherExe '__run'
    Assert-Case 'running runner keeps the MSI exe in use' (-not (Test-Released $msiExe)) 'exclusive open succeeded while the runner was running'
    $result = Invoke-Helper 'Stop'
    Assert-Case 'stop exits successfully' ($result.Code -eq 0) $result.Output
    Assert-Case 'runner is gone' (-not (Test-Alive $runner.Id)) $result.Output
    Assert-Case 'agent process is gone' (-not (Test-Alive $agent)) $result.Output
    Assert-Case 'MSI exe is released' (Test-Released $msiExe) $result.Output
    Assert-Case 'other installation keeps running' (Test-Alive $otherRunner.Id) $result.Output
    Assert-Case 'stop logs both processes' ($result.Output -match 'stopped runner' -and $result.Output -match 'stopped agent process') $result.Output
    Assert-Case 'restart marker names the MSI exe' ((Test-Path -LiteralPath $marker) -and (Get-Content -LiteralPath $marker) -eq $msiExe) $result.Output
    Stop-TestProcesses

    Write-Output 'Stop: an open pidash tui is not a runner'
    $runner = Start-StandIn $msiExe '__run'
    $tui = Start-StandIn $msiExe 'tui'
    $result = Invoke-Helper 'Stop'
    Assert-Case 'stop with tui exits successfully' ($result.Code -eq 0) $result.Output
    Assert-Case 'runner is gone despite tui' (-not (Test-Alive $runner.Id)) $result.Output
    Assert-Case 'tui is left for Windows to ask about' ((Test-Alive $tui.Id) -and $result.Output -match "pid $($tui.Id) still uses") $result.Output
    Stop-TestProcesses

    Write-Output 'Stop: nothing running'
    Set-Content -LiteralPath $marker -Value 'stale'
    $result = Invoke-Helper 'Stop'
    Assert-Case 'idle stop exits successfully' ($result.Code -eq 0 -and $result.Output -match 'no runner is running') $result.Output
    Assert-Case 'idle stop clears a stale marker' (-not (Test-Path -LiteralPath $marker)) $result.Output

    Write-Output 'Restart'
    $result = Invoke-Helper 'Restart' @{ Task = 'present'; Target = $msiExe }
    Assert-Case 'no marker: nothing started' ($result.Code -eq 0 -and $result.Output -notmatch 'FAKE-START' -and $result.Output -match 'nothing to restart') $result.Output

    $cases = @(
        @{ Name = 'owned task'; Fake = @{ Task = 'present'; Target = "`"$msiExe`"" }; Start = $true; Code = 0; Text = 'runner started (pid' },
        @{ Name = 'another installation''s task'; Fake = @{ Task = 'present'; Target = $otherExe }; Start = $false; Code = 0; Text = 'leaving it' },
        @{ Name = 'disabled task'; Fake = @{ Task = 'disabled'; Target = $msiExe }; Start = $false; Code = 0; Text = 'is disabled' },
        @{ Name = 'missing task'; Fake = @{ Task = 'missing' }; Start = $false; Code = 0; Text = 'pidash start' },
        @{ Name = 'start denied'; Fake = @{ Task = 'present'; Target = $msiExe; Start = 'deny' }; Start = $false; Code = 1; Text = 'administrator PowerShell' }
    )
    foreach ($case in $cases) {
        Set-Content -LiteralPath $marker -Value $msiExe
        $result = Invoke-Helper 'Restart' $case.Fake
        Assert-Case "restart, $($case.Name): exit code" ($result.Code -eq $case.Code) $result.Output
        Assert-Case "restart, $($case.Name): start behavior" (($result.Output -match 'FAKE-START') -eq $case.Start) $result.Output
        Assert-Case "restart, $($case.Name): explanation" ($result.Output -match [regex]::Escape($case.Text)) $result.Output
        Assert-Case "restart, $($case.Name): marker cleared" (-not (Test-Path -LiteralPath $marker)) $result.Output
        Stop-TestProcesses
    }

    Set-Content -LiteralPath $marker -Value $msiExe
    $runner = Start-StandIn $msiExe '__run'
    $result = Invoke-Helper 'Restart' @{ Task = 'present'; Target = $msiExe }
    Assert-Case 'restart, runner already running: not started twice' ($result.Output -notmatch 'FAKE-START' -and $result.Output -match 'already running') $result.Output
    Stop-TestProcesses

    Write-Output 'Uninstall'
    $cases = @(
        @{ Name = 'task is absent'; Fake = @{ Task = 'missing' }; Remove = $false; Text = 'nothing to remove' },
        @{ Name = 'task belongs to another install'; Fake = @{ Task = 'present'; Target = $otherExe }; Remove = $false; Text = 'leaving it' },
        @{ Name = 'task belongs to this MSI'; Fake = @{ Task = 'present'; Target = $msiExe }; Remove = $true; Text = 'removed scheduled task' },
        @{ Name = 'quoted task path belongs to this MSI'; Fake = @{ Task = 'present'; Target = "`"$msiExe`"" }; Remove = $true; Text = 'removed scheduled task' },
        @{ Name = 'task query fails'; Fake = @{ Task = 'error' }; Remove = $false; Text = 'cleanup skipped' }
    )
    foreach ($case in $cases) {
        Set-Content -LiteralPath $marker -Value $msiExe
        $result = Invoke-Helper 'Uninstall' $case.Fake
        Assert-Case "uninstall, $($case.Name): exits successfully" ($result.Code -eq 0) $result.Output
        Assert-Case "uninstall, $($case.Name): stop and remove behavior" ((($result.Output -match 'FAKE-STOP') -eq $case.Remove) -and (($result.Output -match 'FAKE-REMOVE') -eq $case.Remove)) $result.Output
        Assert-Case "uninstall, $($case.Name): explanation" ($result.Output -match [regex]::Escape($case.Text)) $result.Output
        Assert-Case "uninstall, $($case.Name): marker cleared" (-not (Test-Path -LiteralPath $marker)) $result.Output
    }

    Write-Output 'MSI packaging'
    [xml] $wix = Get-Content -Raw -LiteralPath $WixSource
    $namespace = New-Object System.Xml.XmlNamespaceManager($wix.NameTable)
    $namespace.AddNamespace('w', 'http://schemas.microsoft.com/wix/2006/wi')
    [xml] $include = Get-Content -Raw -LiteralPath $WixInclude
    $run = $include.Include.Property.Value

    $committed = [System.IO.File]::ReadAllText((Resolve-Path $WixInclude).Path) -replace "`r`n", "`n"
    Assert-Case 'embedded helper matches pidash-msi-lifecycle.ps1 (rerun this test with -Update)' ($committed -ceq (Get-LifecycleInclude)) 'pidash-msi-lifecycle.wxi is stale'
    Assert-Case 'main.wxs includes the embedded helper' ((Get-Content -Raw -LiteralPath $WixSource) -match '<\?include pidash-msi-lifecycle\.wxi \?>') 'include not found'
    Assert-Case 'no schtasks.exe calls remain' ((Get-Content -Raw -LiteralPath $WixSource) -notmatch 'schtasks') 'main.wxs still calls schtasks.exe'

    function Get-Template([string] $id) {
        $node = $wix.SelectSingleNode("//w:SetProperty[@Id='$id']", $namespace)
        if ($node) { return $node.Value }
        $node = $wix.SelectSingleNode("//w:Property[@Id='$id']", $namespace)
        if ($node) { return $node.Value }
        return $wix.SelectSingleNode("//w:CustomAction[@Id='$id']", $namespace).ExeCommand
    }

    # Windows Installer formats each command once, inserting property values
    # verbatim. Only these properties may appear in the templates.
    function Format-Msi([string] $template) {
        $formatted = $template.Replace('[System64Folder]', "$env:SystemRoot\System32\").Replace('[SystemFolder]', "$env:SystemRoot\SysWOW64\").Replace('[Bin]', "$binDir\")
        $formatted = $formatted.Replace('[PidashLifecycleRun]', $run)
        $formatted
    }

    $templates = [ordered]@{
        WixQuietExec64CmdLine = 'Stop'
        PidashRestartRunner = 'Restart'
        PidashRestartRunnerOnRollback = 'Restart'
        WixQuietExecCmdLine = 'Restart'
        RemovePidashTaskOnUninstall = 'Uninstall'
    }
    foreach ($id in $templates.Keys) {
        $template = Get-Template $id
        $unknown = [regex]::Matches($template, '\[[^\]]*\]') | Where-Object { $_.Value -notin '[System64Folder]', '[SystemFolder]', '[Bin]', '[PidashLifecycleRun]' }
        Assert-Case "$id fits CustomAction.Target (255)" ($template.Length -le 255) "$($template.Length) characters"
        Assert-Case "$id uses only known properties" (-not $unknown) ($unknown -join ', ')
        Assert-Case "$id runs mode $($templates[$id])" ($template -match "-Mode $($templates[$id]) ") $template
        Assert-Case "$id fits a Windows command line" ((Format-Msi $template).Length -lt 32000) "$((Format-Msi $template).Length) characters"
    }

    # Run the Stop command exactly as Windows Installer will, with ProgramData
    # pointed at the test directory so the marker lands there.
    $runner = Start-StandIn $msiExe '__run'
    $command = Format-Msi (Get-Template 'WixQuietExec64CmdLine')
    $split = [regex]::Match($command, '^"([^"]+)" (.*)$', 'Singleline')
    $start = New-Object System.Diagnostics.ProcessStartInfo($split.Groups[1].Value, $split.Groups[2].Value)
    $start.UseShellExecute = $false
    $start.RedirectStandardOutput = $true
    $start.RedirectStandardError = $true
    $start.EnvironmentVariables['ProgramData'] = $work
    $process = [System.Diagnostics.Process]::Start($start)
    $stdout = $process.StandardOutput.ReadToEnd() + $process.StandardError.ReadToEnd()
    $process.WaitForExit()
    Assert-Case 'MSI-formatted Stop command stops the runner' ($process.ExitCode -eq 0 -and -not (Test-Alive $runner.Id) -and $stdout -match 'stopped runner') $stdout
    Assert-Case 'MSI-formatted Stop command records the restart' (Test-Path -LiteralPath (Join-Path $work 'pidash\msi-restart-runner')) $stdout
    Stop-TestProcesses

    function Get-Action([string] $id) { $wix.SelectSingleNode("//w:CustomAction[@Id='$id']", $namespace) }
    function Get-Scheduled([string] $id) { $wix.SelectSingleNode("//w:InstallExecuteSequence/w:Custom[@Action='$id']", $namespace) }
    $upgradeOrUninstall = '(WIX_UPGRADE_DETECTED AND NOT (REMOVE~="ALL")) OR (REMOVE~="ALL" AND NOT UPGRADINGPRODUCTCODE)'

    $stop = Get-Action 'PidashStopRunner'
    Assert-Case 'stop is a logged immediate action' ($stop.DllEntry -eq 'WixQuietExec64' -and $stop.Execute -eq 'immediate' -and $stop.Return -eq 'ignore') $stop.OuterXml
    $stopAt = Get-Scheduled 'PidashStopRunner'
    Assert-Case 'stop runs before InstallValidate on upgrade and uninstall' ($stopAt.Before -eq 'InstallValidate' -and $stopAt.InnerText -eq $upgradeOrUninstall) $stopAt.OuterXml

    $restart = Get-Action 'PidashRestartRunner'
    Assert-Case 'restart is a SYSTEM commit action' ($restart.DllEntry -eq 'WixQuietExec64' -and $restart.Execute -eq 'commit' -and $restart.Impersonate -eq 'no' -and $restart.Return -eq 'ignore') $restart.OuterXml
    $restartAt = Get-Scheduled 'PidashRestartRunner'
    Assert-Case 'restart is scheduled for upgrades only' ($restartAt.Before -eq 'InstallFinalize' -and $restartAt.InnerText -eq 'WIX_UPGRADE_DETECTED AND NOT (REMOVE~="ALL")') $restartAt.OuterXml

    $rollback = Get-Action 'PidashRestartRunnerOnRollback'
    Assert-Case 'rollback restart is a SYSTEM rollback action' ($rollback.DllEntry -eq 'WixQuietExec64' -and $rollback.Execute -eq 'rollback' -and $rollback.Impersonate -eq 'no' -and $rollback.Return -eq 'ignore') $rollback.OuterXml
    $rollbackAt = Get-Scheduled 'PidashRestartRunnerOnRollback'
    # Anything between InstallInitialize and RemoveExistingProducts makes
    # Windows Installer abort the upgrade with error 2613.
    Assert-Case 'rollback restart follows RemoveExistingProducts' ($rollbackAt.After -eq 'RemoveExistingProducts' -and $rollbackAt.InnerText -eq $upgradeOrUninstall) $rollbackAt.OuterXml
    $between = $wix.SelectNodes("//w:InstallExecuteSequence/w:Custom[@After='InstallInitialize' or @Before='RemoveExistingProducts']", $namespace)
    Assert-Case 'nothing sits between InstallInitialize and RemoveExistingProducts' ($between.Count -eq 0) (($between | ForEach-Object { $_.OuterXml }) -join "`n")

    foreach ($exit in 'Cancel', 'Error') {
        $action = Get-Action "PidashRestartRunnerOn$exit"
        $at = Get-Scheduled "PidashRestartRunnerOn$exit"
        # A plain EXE action is killed with 0xC000013A when msiexec exits.
        Assert-Case "restart on $($exit.ToLower()) is a logged best-effort action" ($action.DllEntry -eq 'WixQuietExec' -and $action.Execute -eq 'immediate' -and $action.Return -eq 'ignore') $action.OuterXml
        Assert-Case "restart on $($exit.ToLower()) is scheduled" ($at.OnExit -eq $exit.ToLower() -and $at.InnerText -eq $upgradeOrUninstall) $at.OuterXml
    }

    $remove = Get-Action 'RemovePidashTaskOnUninstall'
    Assert-Case 'uninstall cleanup runs as SYSTEM' ($remove.DllEntry -eq 'WixQuietExec64' -and $remove.Execute -eq 'deferred' -and $remove.Impersonate -eq 'no' -and $remove.Return -eq 'ignore') $remove.OuterXml
    $removeAt = Get-Scheduled 'RemovePidashTaskOnUninstall'
    Assert-Case 'real uninstall removes task before files' ($removeAt.Before -eq 'RemoveFiles' -and $removeAt.InnerText -eq 'REMOVE~="ALL" AND NOT UPGRADINGPRODUCTCODE') $removeAt.OuterXml
} finally {
    Stop-TestProcesses
    foreach ($name in $testVariables) { [Environment]::SetEnvironmentVariable($name, $originalVariables[$name]) }
    Remove-Item -Recurse -Force -LiteralPath $work -ErrorAction SilentlyContinue
}

Write-Output ''
if ($failures.Count -gt 0) {
    Write-Output "$($failures.Count) failed, $passed passed"
    foreach ($failure in $failures) { Write-Output "---- $failure" }
    exit 1
}
Write-Output "all $passed checks passed"
exit 0
