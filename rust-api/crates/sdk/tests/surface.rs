#![allow(unused_imports)]
//! Surface snapshot: `SURFACE.txt` must list exactly the re-exports below.
//!
//! Each entry proves its path resolves (the `use` fails to compile when
//! the export is removed or renamed) and contributes its snapshot string.
//! The comparison is sorted, so entry order here does not matter, but keep
//! the list sorted anyway for reviewable diffs. `SURFACE.txt` itself must
//! be sorted (same reason).
//!
//! This catches removals and renames, not additions: a `pub use` added to
//! `src/lib.rs` without a matching entry here (and in `SURFACE.txt`) goes
//! unnoticed by this test. That is by design — additions cannot break the
//! overlay — and review covers the three-file update.

macro_rules! surface_snapshot {
    ($( $module:ident :: $name:ident ),* $(,)?) => {
        const SURFACE_PATHS: &[&str] = &[
            $(concat!("pidash_sdk::", stringify!($module), "::", stringify!($name))),*
        ];

        #[test]
        fn surface_matches_snapshot() {
            // Existence proof: each import must resolve. Block-scoped so
            // the same leaf name may appear in several modules.
            $(
                { use pidash_sdk::$module::$name; }
            )*

            let mut expected = SURFACE_PATHS.to_vec();
            expected.sort_unstable();
            let actual: Vec<&str> = include_str!("../SURFACE.txt")
                .lines()
                .map(str::trim)
                .filter(|l| !l.is_empty() && !l.starts_with('#'))
                .collect();
            let mut sorted = actual.clone();
            sorted.sort_unstable();
            assert_eq!(
                actual, sorted,
                "SURFACE.txt is not sorted; sort its pidash_sdk:: lines"
            );
            if actual != expected {
                let missing: Vec<&&str> =
                    expected.iter().filter(|e| !actual.contains(e)).collect();
                let extra: Vec<&&str> =
                    actual.iter().filter(|a| !expected.contains(a)).collect();
                panic!(
                    "sdk surface drift: {} missing from SURFACE.txt, {} extra in SURFACE.txt.\n\
                     missing (in code, not in snapshot): {:?}\n\
                     extra (in snapshot, not in code): {:?}\n\
                     If the change is intentional, update src/lib.rs, tests/surface.rs \
                     and SURFACE.txt together.",
                    missing.len(),
                    extra.len(),
                    missing,
                    extra,
                );
            }
        }
    };
}

