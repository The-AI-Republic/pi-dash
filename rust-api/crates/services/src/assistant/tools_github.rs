    #[test]
    fn non_ascii_digits_match_python() {
        // GitHub: `re` `\d` matches Unicode decimal digits and `int()`
        // canonicalizes (`github_client.py:260-275`).
        let parsed = parse_github_review_url("https://github.com/acme/web/pull/\u{664}\u{662}")
            .expect("parses");
        assert_eq!(parsed.external_iid, "42");
        assert_eq!(parsed.url, "https://github.com/acme/web/pull/42");
        // Mixed scripts, leading zeros: positional value, like `int()`.
        let parsed = parse_github_review_url("https://github.com/acme/web/pull/0\u{664}\u{662}")
            .expect("parses");
        assert_eq!(parsed.external_iid, "42");
        // `\d` is decimal-only: superscripts, fractions, numerals reject.
        for digits in ["\u{b2}", "\u{bd}", "\u{2167}"] {
            let url = format!("https://github.com/acme/web/pull/{digits}");
            assert!(parse_github_review_url(&url).is_none(), "{digits:?}");
        }
        // GitLab: `isdigit` keeps the raw string, no `int()` round-trip
        // (`gitlab.py:269-281`).
        let parsed = parse_gitlab_review_url(
            "https://gitlab.com/g/r/-/merge_requests/\u{664}\u{662}",
            &[],
        )
        .expect("parses");
        assert_eq!(parsed.external_iid, "\u{664}\u{662}");
        assert_eq!(
            parsed.url,
            "https://gitlab.com/g/r/-/merge_requests/\u{664}\u{662}"
        );
        let parsed = parse_gitlab_review_url("https://gitlab.com/g/r/-/merge_requests/\u{b2}", &[])
            .expect("parses");
        assert_eq!(parsed.external_iid, "\u{b2}");
        for digits in ["\u{bd}", "\u{2167}"] {
            let url = format!("https://gitlab.com/g/r/-/merge_requests/{digits}");
            assert!(parse_gitlab_review_url(&url, &[]).is_none(), "{digits:?}");
        }
    }

