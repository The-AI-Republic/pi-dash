// License-header check for the new trees (F-01; interim AGPL text in F-11/NEWFRONT-22).
// The single definition lives in apps/web_new/LICENSE_HEADER.txt. A source
// file passes when it carries the three header lines (copyright, SPDX
// identifier, LICENSE pointer) and never the old tree's copyright line,
// which trips the copied-file wire.
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const trees = ["apps/web_new", "packages/kit", "packages/api-client"];
const extensions = new Set([".ts", ".tsx", ".mts", ".cts", ".mjs", ".cjs", ".css"]);
// coverage/ is generated by `test:coverage` (lcov's HTML report carries CSS
// without our header); like dist/ it is never hand-written.
const skipDirs = new Set(["node_modules", "dist", ".turbo", "coverage"]);
// Generated router tree; F-02 similarity check ignores generated files too.
const skipFiles = new Set(["routeTree.gen.ts", ".gitkeep"]);

function check(full, root, failures) {
  const text = readFileSync(full, "utf8");
  const rel = relative(root, full);
  // Built at runtime so this script does not literally contain the string it bans.
  const oldCopyright = ["Copyright (c) 2023-present", "Pi Dash Software, Inc. and contributors"].join(" ");
  if (text.includes(oldCopyright)) {
    failures.push(`${rel}: carries the old tree's copyright line (copied file?)`);
    return;
  }
  const required = [
    "Copyright (c) Pi Dash contributors",
    "SPDX-License-Identifier: AGPL-3.0-only",
    "See the LICENSE file for details.",
  ];
  const missing = required.filter((line) => !text.includes(line));
  if (missing.length > 0) {
    failures.push(`${rel}: missing the license header from LICENSE_HEADER.txt (${missing.join("; ")})`);
  }
}

// Walk the new trees and return one message per offending file. `root` and
// `trees` default to this checkout; the self-test drives it over a hermetic
// fixture repo, the same way the similarity check is tested.
function runHeaderCheck({ root: scanRoot = root, trees: scanTrees = trees } = {}) {
  const failures = [];

  function walk(dir) {
    for (const entry of readdirSync(dir)) {
      if (skipDirs.has(entry) || skipFiles.has(entry)) continue;
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) {
        walk(full);
      } else if ([...extensions].some((ext) => entry.endsWith(ext))) {
        check(full, scanRoot, failures);
      }
    }
  }

  for (const tree of scanTrees) {
    const treeRoot = join(scanRoot, tree);
    // Only an absent tree root is tolerated (an optional package may not be
    // checked out). Probe the root before walking so an ENOENT deeper in the
    // walk (e.g. a dangling symlink) is reported instead of hiding the tree.
    try {
      statSync(treeRoot);
    } catch (error) {
      if (error?.code === "ENOENT") continue;
      throw error;
    }
    walk(treeRoot);
  }
  return failures;
}

// Returns the process exit code and leaves exiting to the caller, so the
// self-test can drive both the pass and the failure branch.
function main(options = {}) {
  const failures = runHeaderCheck(options);
  if (failures.length > 0) {
    console.error("License header check failed:");
    for (const failure of failures) console.error(`  - ${failure}`);
    return 1;
  }
  console.log("License header check passed.");
  return 0;
}

// True when this module is the process entry point. Exported so the self-test
// can cover it without relying on a child process's coverage.
function isCliEntry(argv1 = process.argv[1]) {
  return argv1 !== undefined && import.meta.url === pathToFileURL(argv1).href;
}

// Stay a pure module when imported (e.g. by the test). When this file is the
// process entry point, exit with main's verdict.
/* v8 ignore next 3 -- child-process bootstrap; the self-test spawns it */
if (isCliEntry()) {
  process.exit(main());
}

export { isCliEntry, main, runHeaderCheck };
