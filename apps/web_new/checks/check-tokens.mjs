// Kit token check (NEWFRONT-683): every custom property referenced through a
// Tailwind `-(--token)` utility or a fallback-less `var(--token)` must be
// defined by the kit. An undefined property makes the declaration invalid at
// computed-value time, so gaps collapse to normal/0, padding to 0, and text to
// the inherited color — silently, because unit tests only assert class strings.
// Definitions come from the `:root` block of packages/kit/src/tokens.css plus
// any `@theme` block in packages/kit/src/kit.css. Only the `src` trees are
// scanned: e2e parity drivers mirror old-app classes (oracle DOM), which use
// old-app tokens by design.
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const trees = ["apps/web_new/src", "packages/kit/src"];
const defaultTokensCss = join(root, "packages", "kit", "src", "tokens.css");
const defaultKitCss = join(root, "packages", "kit", "src", "kit.css");
const extensions = new Set([".ts", ".tsx", ".mts", ".cts", ".mjs", ".cjs", ".css"]);
// coverage/ is generated by `test:coverage`; like dist/ it is never hand-written.
const skipDirs = new Set(["node_modules", "dist", ".turbo", "coverage"]);
// Generated router tree; the similarity check ignores generated files too.
const skipFiles = new Set(["routeTree.gen.ts", ".gitkeep"]);

// Contents of the first `selector { ... }` block, brace-matched so nested
// rules (e.g. the OS-follow `@media` block) do not cut it short. Returns null
// when the selector is absent so an optional file can define no tokens.
function blockContents(css, selector) {
  const start = css.indexOf(selector);
  if (start === -1) return null;
  const open = css.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < css.length; i += 1) {
    if (css[i] === "{") depth += 1;
    if (css[i] === "}") {
      depth -= 1;
      if (depth === 0) return css.slice(open + 1, i);
    }
  }
  return null;
}

function definedTokens(tokensCssPath, kitCssPath) {
  const defined = new Set();
  // Comments are stripped first so a commented-out `--foo:` never counts as
  // a definition and a selector name inside prose never opens a block.
  const tokensCss = stripBlockComments(readFileSync(tokensCssPath, "utf8"));
  // Only `:root` counts as a definition: a token overridden per theme but
  // missing from `:root` is undefined in every other theme, which is exactly
  // the bug this check guards against.
  const base = blockContents(tokensCss, ":root");
  if (base !== null) {
    for (const match of base.matchAll(/(--[\w-]+)\s*:/g)) defined.add(match[1]);
  }
  let kitCss = "";
  try {
    kitCss = stripBlockComments(readFileSync(kitCssPath, "utf8"));
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  // `@theme` blocks may each contribute tokens; scan every one of them.
  let from = 0;
  for (;;) {
    const at = kitCss.indexOf("@theme", from);
    if (at === -1) break;
    const open = kitCss.indexOf("{", at);
    if (open === -1) break;
    let depth = 0;
    let close = -1;
    for (let i = open; i < kitCss.length; i += 1) {
      if (kitCss[i] === "{") depth += 1;
      if (kitCss[i] === "}") {
        depth -= 1;
        if (depth === 0) {
          close = i;
          break;
        }
      }
    }
    if (close === -1) break;
    const theme = kitCss.slice(open + 1, close);
    for (const match of theme.matchAll(/(--[\w-]+)\s*:/g)) defined.add(match[1]);
    from = close + 1;
  }
  return defined;
}

// Block comments with newlines blanked to spaces would shift every later line
// number, so the comment text is masked but its newlines are kept.
function stripBlockComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, (comment) => comment.replace(/[^\n]/g, " "));
}

function lineOf(text, index) {
  let line = 1;
  for (let i = 0; i < index; i += 1) {
    if (text[i] === "\n") line += 1;
  }
  return line;
}

function checkFile(full, scanRoot, defined, failures, seen) {
  const text = stripBlockComments(readFileSync(full, "utf8"));
  const rel = relative(scanRoot, full);
  const candidates = [];
  // Tailwind arbitrary-value shorthand: `p-(--space-4)` compiles to
  // `padding: var(--space-4)` with no fallback, so the token must exist.
  for (const match of text.matchAll(/-\(--[\w-]+\)/g)) {
    candidates.push({ name: match[0].slice(2, -1), index: match.index ?? 0 });
  }
  // A `var()` with a fallback stays valid when the property is missing, so
  // only the fallback-less form is checked.
  for (const match of text.matchAll(/var\(\s*(--[\w-]+)\s*([,)])/g)) {
    if (match[2] === ",") continue;
    candidates.push({ name: match[1], index: match.index ?? 0 });
  }
  // File order, so the report reads top to bottom.
  candidates.sort((a, b) => a.index - b.index);
  for (const { name, index } of candidates) {
    if (defined.has(name)) continue;
    const key = `${rel}:${lineOf(text, index)}:${name}`;
    if (seen.has(key)) continue;
    seen.add(key);
    failures.push(`${rel}:${lineOf(text, index)}: ${name} is not defined by the kit (packages/kit/src/tokens.css)`);
  }
}

// Walk the new `src` trees and return one message per undefined token
// reference. `root` and `trees` default to this checkout and the definition
// files default to the shipped kit CSS; the self-test drives all of them over
// a hermetic fixture repo, the same way the header check is tested.
function runTokenCheck({
  root: scanRoot = root,
  trees: scanTrees = trees,
  tokensCss = defaultTokensCss,
  kitCss = defaultKitCss,
} = {}) {
  const defined = definedTokens(tokensCss, kitCss);
  const failures = [];
  const seen = new Set();

  function walk(dir) {
    for (const entry of readdirSync(dir)) {
      if (skipDirs.has(entry) || skipFiles.has(entry)) continue;
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) {
        walk(full);
      } else if ([...extensions].some((ext) => entry.endsWith(ext))) {
        checkFile(full, scanRoot, defined, failures, seen);
      }
    }
  }

  for (const tree of scanTrees) {
    const treeRoot = join(scanRoot, tree);
    // Only an absent tree root is tolerated (an optional package may not be
    // checked out). Probe the root before walking so an ENOENT deeper in the
    // walk (e.g. a dangling symlink) is reported instead of hiding the tree.
    try {
      statSync(treeRoot);
    } catch (error) {
      if (error?.code === "ENOENT") continue;
      throw error;
    }
    walk(treeRoot);
  }
  return failures;
}

// Returns the process exit code and leaves exiting to the caller, so the
// self-test can drive both the pass and the failure branch.
function main(options = {}) {
  const failures = runTokenCheck(options);
  if (failures.length > 0) {
    console.error("Token check failed:");
    for (const failure of failures) console.error(`  - ${failure}`);
    return 1;
  }
  console.log("Token check passed.");
  return 0;
}

// True when this module is the process entry point. Exported so the self-test
// can cover it without relying on a child process's coverage.
function isCliEntry(argv1 = process.argv[1]) {
  return argv1 !== undefined && import.meta.url === pathToFileURL(argv1).href;
}

// Stay a pure module when imported (e.g. by the test). When this file is the
// process entry point, exit with main's verdict.
/* v8 ignore next 3 -- child-process bootstrap; the self-test spawns it */
if (isCliEntry()) {
  process.exit(main());
}

export { isCliEntry, main, runTokenCheck };
