    expect(ADMIN_SEGMENT_LABELS).toBeDefined();
    expect(ADMIN_SIDEBAR_ENTRIES.length).toBeGreaterThan(0);
    expect(COMPANY_NAME_MAX_LENGTH).toBeGreaterThan(0);
    expect(PERSON_NAME_MAX_LENGTH).toBeGreaterThan(0);
